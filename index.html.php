<h2>アーカイブ済み</h2>
<p>Packagist 1系のメタデータは <a href="https://packagist.org">packagist.org</a> では配信されなくなったため、Packagist 1系ミラーである Packagist.JP の運営を終了し、リポジトリをアーカイブしました。</p>
<p>Packagist 2系（v2 API）に対応した新しいミラーは現在提供していません。今後は <a href="https://packagist.org">https://packagist.org</a> をご利用ください。</p>

<h2>Archived</h2>
<p>Packagist 1.x metadata is no longer distributed by <a href="https://packagist.org">packagist.org</a> (v1 API has been deprecated). As a result, this Packagist 1.x mirror (Packagist.JP) has been discontinued and the repository has been archived.</p>
<p>Please use the official <a href="https://packagist.org">packagist.org</a> instead.</p>

